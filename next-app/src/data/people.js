/** Returns a person by their slug. */
export function getPersonBySlug(slug) {
  return people.find((p) => p.slug === slug) || null;
}

/** Returns all people. */
export function getAllPeople() {
  return people;
}

/**
 * Resolves a blog author string to a person data object.
 * Accepts display name strings like "Ved Parkash" or "Sandeep Kumar".
 * Returns null for unknown authors (e.g. "Vayunex Team") — never breaks.
 */
export function resolveAuthorToPerson(authorName) {
  if (!authorName) return null;
  const normalized = authorName.trim().toLowerCase();
  return (
    people.find(
      (p) =>
        p.name.toLowerCase() === normalized ||
        p.id === normalized.replace(/\s+/g, '-')
    ) || null
  );
}
